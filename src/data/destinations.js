export function getDestination(id, city) {
  const known = destinations.find((d) => d.id === id);
  if (known) return known;
  return {
    id,
    name: city?.name || "Yeni şehir",
    country: city?.country || "",
    region: city?.region || "",
    subtitle: "Yeni bir şehir, sana ait bir hikâye.",
    image: "/images/world.svg",
    generic: true,
    places: [],
    latitude: city?.latitude,
    longitude: city?.longitude,
  };
}
